-- ---------------------------------------------------------------------------
-- 1. bank_users – system login accounts
--    One row per person who can authenticate (customers, tellers, admins …)
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS bank_users (
    user_id         SERIAL PRIMARY KEY,

    -- Unique login name (case-insensitive lookup in application layer)
    username        VARCHAR(100) UNIQUE NOT NULL,

    -- PBKDF2-HMAC-SHA256 credential string produced by PasswordHasher.hash()
    -- Format: pbkdf2sha256:<iterations>:<base64(salt)>:<base64(hash)>
    password_hash   VARCHAR(512) NOT NULL,

    -- Role enum value: CUSTOMER, TELLER, BRANCH_MANAGER, AUDITOR, ADMIN
    role            VARCHAR(20)  NOT NULL
                    CHECK (role IN ('CUSTOMER','TELLER','BRANCH_MANAGER','AUDITOR','ADMIN')),

    -- Links a CUSTOMER-role user to their account-holder record (nullable for staff)
    customer_id     INT REFERENCES customers(customer_id) ON DELETE SET NULL,

    -- Account-lockout tracking
    failed_attempts INT          NOT NULL DEFAULT 0
                    CHECK (failed_attempts >= 0),
    is_locked       BOOLEAN      NOT NULL DEFAULT FALSE,

    -- Timestamps
    created_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_login_at   TIMESTAMP
);

-- Index used by AuthService for fast username lookup
CREATE INDEX IF NOT EXISTS idx_bank_users_username
    ON bank_users (username);

-- Partial index to quickly find all locked accounts (admin dashboard)
CREATE INDEX IF NOT EXISTS idx_bank_users_locked
    ON bank_users (is_locked)
    WHERE is_locked = TRUE;


-- ---------------------------------------------------------------------------
-- 2. security_audit_log – immutable audit trail
--    Rows are INSERT-only (never UPDATE or DELETE in normal operation).
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS security_audit_log (
    event_id       BIGSERIAL PRIMARY KEY,

    -- Short event type label (e.g. LOGIN_SUCCESS, TRANSFER, ACCESS_DENIED)
    event_type     VARCHAR(50)   NOT NULL,

    -- Who performed the action ('SYSTEM' when no user session is active)
    username       VARCHAR(100)  NOT NULL DEFAULT 'SYSTEM',

    -- Optional: which bank account was involved
    account_number BIGINT        REFERENCES accounts(account_number) ON DELETE SET NULL,

    -- Full event description (truncated to 2000 chars by AuditDAO)
    details        TEXT          NOT NULL,

    -- Client IP address (best-effort; nullable if not available)
    ip_address     VARCHAR(45),

    -- UTC event timestamp – set by DB default so it cannot be spoofed by app
    occurred_at    TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Auditors / admins need fast lookups by type and by account.
CREATE INDEX IF NOT EXISTS idx_audit_event_type
    ON security_audit_log (event_type, occurred_at DESC);

CREATE INDEX IF NOT EXISTS idx_audit_account
    ON security_audit_log (account_number, occurred_at DESC)
    WHERE account_number IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_audit_username
    ON security_audit_log (username, occurred_at DESC);


